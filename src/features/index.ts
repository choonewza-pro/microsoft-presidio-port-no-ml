export function getByCountry(countryCode: string | null) {
  if (!countryCode) return allFeatures;
  const lower = countryCode.toLowerCase();
  const filtered: Record<string, any> = {};
  for (const [k, v] of Object.entries(allFeatures)) {
    if ((v as any).COUNTRY_CODE === lower) filtered[k] = v;
    if ((v as any).COUNTRY_CODE === null && lower === "global") filtered[k] = v;
  }
  return Object.keys(filtered).length ? filtered : null;
}
export function getByEntity(entityType: string) {
  for (const v of Object.values(allFeatures)) if ((v as any).ENTITY_TYPE === entityType) return v;
  return null;
}
